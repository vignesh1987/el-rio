/**
 * Debrief: compares the silo plans, the player's council plan and the
 * cheapest plan that works. Then states four lessons, each backed by a
 * number from the player's own game.
 */
import type { ReferenceResult } from "../../model/reference.ts";
import type { MinistryId, Outcome, Scenario } from "../../model/types.ts";
import { fmt, money, pct } from "../format.ts";
import { MINISTRIES, shortName } from "../game.ts";

interface DebriefProps {
  scenario: Scenario;
  player: MinistryId;
  silo: Outcome;
  council: Outcome;
  reference: ReferenceResult | null;
  hintsUsed: number;
  onPlayAnother: (m: MinistryId) => void;
  onRevise: () => void;
  onHome: () => void;
}

export function Debrief({ scenario, player, silo, council, reference, hintsUsed, onPlayAnother, onRevise, onHome }: DebriefProps) {
  const failedCount = (o: Outcome) => o.checks.filter((c) => !c.ok).length;
  const ref = reference?.outcome;
  const nextMinistry = MINISTRIES[(MINISTRIES.indexOf(player) + 1) % MINISTRIES.length];

  // Rows of the comparison table: label and a formatter applied to each outcome.
  const rows: [string, (o: Outcome) => string][] = [
    ["Checks failed", (o) => `${failedCount(o)} of ${o.checks.length}`],
    ["Blackouts", (o) => `${fmt(o.shortfallTWh)} TWh`],
    ["Grain delivered", (o) => `${fmt(o.foodDeliveredMt)} Mt`],
    ["City water delivered", (o) => `${fmt(o.cityWaterDeliveredBcm, 2)} bcm`],
    ["Aquifer overdraft", (o) => `${fmt(o.aquiferOverdraftBcm)} bcm`],
    ["River flow at the dams", (o) => `${pct(o.hydroFlowFactor)} of natural`],
    ["Land used", (o) => `${fmt(o.landUseMha, 2)} of ${fmt(scenario.limits.landMha)} Mha`],
    ["Power-sector CO₂", (o) => `${fmt(o.co2Mt)} Mt`],
    ["Cost per year", (o) => money(o.costTotal)],
  ];

  const extraCost = council.costTotal / silo.costTotal - 1;

  return (
    <div class="stack">
      <div class="round-head">
        <h1 style={{ color: "var(--ink)" }}>What the Council learned</h1>
      </div>

      <div class="panel table-wrap">
        <table class="plans-table">
          <thead>
            <tr>
              <th />
              <th>Silo plans</th>
              <th>Your council plan</th>
              <th>Cheapest working plan</th>
            </tr>
          </thead>
          <tbody>
            {rows.map(([label, f]) => (
              <tr key={label}>
                <td>{label}</td>
                <td class="num">{f(silo)}</td>
                <td class="num">{f(council)}</td>
                <td class="num">{ref ? f(ref) : "Calculating…"}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      {ref && (
        <p class="muted" style={{ maxWidth: "70ch" }}>
          {council.costTotal <= ref.costTotal + 0.5
            ? "Your council plan matches the cheapest working plan."
            : `Your council plan costs ${money(council.costTotal - ref.costTotal)} a year more than the cheapest working plan. Try again to close the gap.`}
          {hintsUsed > 0 ? ` You used ${hintsUsed} hint${hintsUsed === 1 ? "" : "s"}.` : " You used no hints."}
        </p>
      )}

      <div class="lessons">
        <div class="panel">
          <h3>Rational alone, broken together</h3>
          <p>
            Each silo plan passed its own checks. Combined, they failed {failedCount(silo)} of {silo.checks.length}. Every ministry counted the same river, aquifer and grid as its own.
          </p>
        </div>
        <div class="panel">
          <h3>Water for energy</h3>
          <p>
            Upstream farms and cities left the dams {pct(silo.hydroFlowFactor)} of natural flow in the silo plans. Your council plan left them {pct(council.hydroFlowFactor)}.
          </p>
        </div>
        <div class="panel">
          <h3>Energy for water</h3>
          <p>
            In the silo plans, pumps and water treatment needed {fmt(silo.demandPumpsTWh + silo.demandWaterSupplyTWh)} TWh that the energy forecast left out. Electricity that is free to one ministry is still generated by another.
          </p>
        </div>
        <div class="panel">
          <h3>The pressure moves</h3>
          <p>
            Your plan uses {pct(council.landUseMha / scenario.limits.landMha)} of the land and {pct(council.co2Mt / scenario.limits.co2CapMt)} of the carbon cap. It costs {pct(Math.abs(extraCost))} {extraCost >= 0 ? "more" : "less"} than the silo plans did on paper. The silo plans were cheap because they spent the same water twice.
          </p>
        </div>
      </div>

      <div class="btn-row">
        <button class="btn" type="button" onClick={() => onPlayAnother(nextMinistry)}>
          Play as {shortName(nextMinistry)}
        </button>
        <button class="btn ghost" type="button" onClick={onRevise}>
          Revise the council plan
        </button>
        <button class="btn ghost" type="button" onClick={onHome}>
          Back to the start
        </button>
      </div>
    </div>
  );
}
